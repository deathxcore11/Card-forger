const escape=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const irregular={Elf:'Elves',Dwarf:'Dwarves',Wolf:'Wolves',Werewolf:'Werewolves',Mouse:'Mice',Ox:'Oxen'};
export const tribePattern=t=>`(?:${escape(t)}|${escape(irregular[t]||(/[^aeiou]y$/.test(t)?t.slice(0,-1)+'ies':/(?:s|x|ch|sh)$/.test(t)?t+'es':t+'s'))})`;
export const keywordPattern=MTG_VOCABULARY['keyword-abilities'].filter(Boolean).sort((a,b)=>b.length-a.length).map(escape).join('|');
export function requestedKeywords(text='') {
 const re=new RegExp('\\b(?:'+keywordPattern+')(?=$|\\W)','gi');
 return [...new Set([...String(text).matchAll(re)].map(m=>MTG_VOCABULARY['keyword-abilities'].find(k=>k.toLowerCase()===m[0].toLowerCase())))];
}
