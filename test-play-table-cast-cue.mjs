import assert from 'node:assert/strict';
import {castCue} from './play-table-audio.js';
assert.equal(castCue({manaCost:'{1}{R}'}),'CAST-R','one colour');
assert.equal(castCue({manaCost:'{2}{W}{W}'}),'CAST-W','repeated colour is still one');
assert.equal(castCue({manaCost:'{G}{U}'}),'CAST-M','two colours');
assert.equal(castCue({manaCost:'{W/U}{B}'}),'CAST-M','hybrid counts');
assert.equal(castCue({manaCost:'{3}'}),'CAST-C','colourless');
assert.equal(castCue({manaCost:''}),'CAST-C','no cost (a free spell) is colourless');
assert.equal(castCue({manaCost:'{2/W}{2/W}'}),'CAST-C','a generic-or-colour symbol with a number is ignored, like the app');
assert.equal(castCue({known:false}),'CARD-008','unknown card keeps the old sound');
assert.equal(castCue(undefined),'CARD-008','no source keeps the old sound');
console.log('cast cue mapping ok');
