import assert from 'node:assert/strict';
import { createPasswordAuth, authError } from './password-auth.js';
const calls = [], auth = {};
for (const method of ['signInWithPassword','signUp','resetPasswordForEmail','updateUser']) auth[method] = async (...args) => { calls.push([method,...args]); return {data:{session:null},error:null}; };
const flow = createPasswordAuth(auth,()=> 'https://cardforge.example/');
await assert.rejects(flow.login('bad','secret'),/valid email/);
await assert.rejects(flow.signup('test@example.com','short','short'),/8 characters/);
await assert.rejects(flow.signup('test@example.com','test passphrase','different'),/don’t match/);
assert.equal(calls.length,0,'invalid inputs never sent to Auth');
await flow.login('test@example.com','test passphrase');
assert.deepEqual(calls[0],['signInWithPassword',{email:'test@example.com',password:'test passphrase'}]);
await flow.signup('test@example.com','test passphrase','test passphrase');
assert.equal(calls[1][1].options.emailRedirectTo,'https://cardforge.example/');
await flow.reset('test@example.com');
assert.deepEqual(calls[2],['resetPasswordForEmail','test@example.com',{redirectTo:'https://cardforge.example/'}]);
await flow.update('new test passphrase','new test passphrase');
assert.deepEqual(calls[3],['updateUser',{password:'new test passphrase'}]);
auth.signInWithPassword = async()=>({error:{code:'invalid_credentials',message:'Invalid login credentials'}});
await assert.rejects(flow.login('test@example.com','test passphrase'),/Email or password is incorrect/);
assert.match(authError({code:'email_not_confirmed'}),/Confirm your email/);
assert.match(authError({code:'email_address_not_authorized'}),/SMTP/);
assert.match(authError({code:'flow_state_not_found'}),/same browser/);
console.log('PASS: password login/signup/reset Auth calls, validation, redirects and actionable errors; no live email sent.');

const { signedOutAccount } = await import('./views.js');
const signup = signedOutAccount({providers:{email:true,google:false}},'signup');
const signupPane = signup.match(/<div id="auth-signup"[\s\S]*?<\/div>/)?.[0];
assert.ok(signupPane,'signup is a separate panel');
assert.match(signupPane,/id="signupEmail" type="email"/,'signup has its own email field');
assert.match(signupPane,/id="signupPassword"/);
assert.match(signupPane,/id="signupConfirm"/);
assert.doesNotMatch(signupPane,/ hidden/,'active signup panel is visible');
assert.match(signup, /id="auth-login"[^>]* hidden/,'login fields hidden while signing up');
const reset = signedOutAccount({providers:{email:true,google:false}},'reset');
assert.match(reset, /id="resetEmail" type="email"/,'reset has an independent email field');
assert.match(reset, /data-enter="forgotPassword"/);
console.log('PASS: independent signup/reset email fields and focused auth panels.');
