// Synthetic cards and decks only. No user deck, external state or target score.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mtgGoldfish, mtgAuraTargetProfile, mtgAuraTargetStatus} from './goldfish.js';
const permanent=(name,type_line,oracle_text='')=>({name,type_line,oracle_text,cmc:1,mana_cost:'{W}',power:/Creature/.test(type_line)?'2':undefined});
const aura=(rule='creature you control')=>permanent('Test Aura','Enchantment — Aura',`Enchant ${rule}\nEnchanted permanent gets +1/+1.`);
const scout=permanent('Test Scout','Creature — Scout');
const artifact=permanent('Test Relic','Artifact');
const plains={name:'Test Plains',type_line:'Basic Land — Plains',cmc:0,oracle_text:'{T}: Add {W}.',produced_mana:['W']};
const own=card=>({card,controller:'self'}), enemy=card=>({card,controller:'opponent'});
const status=(c,ps)=>mtgAuraTargetStatus(c,ps);
assert.equal(mtgAuraTargetProfile(scout).status,'not-aura');
assert.equal(status(scout,[]).castable,true);
assert.equal(status(aura(),[]).status,'no-target');
assert.equal(status(aura(),[own(scout)]).status,'eligible');
assert.equal(status(aura(),[enemy(scout)]).castable,false);
assert.equal(status(aura('creature an opponent controls'),[own(scout)]).castable,false);
assert.equal(status(aura('creature an opponent controls'),[enemy(scout)]).castable,true);
assert.equal(status(aura('creature'),[enemy(scout)]).castable,true);
assert.equal(status(aura(),[own(artifact),own(plains)]).castable,false);
assert.equal(status(aura('artifact or creature'),[own(artifact)]).castable,true);
assert.equal(status(aura('artifact or creature'),[own(scout)]).castable,true);
assert.equal(status(aura('artifact or creature you control'),[enemy(artifact)]).castable,false);
assert.equal(status(aura('land'),[own(plains)]).castable,true);
assert.equal(status(aura('land'),[own(scout)]).castable,false);
assert.equal(status(aura('nonland permanent'),[own(plains)]).castable,false);
assert.equal(status(aura('nonland permanent'),[own(artifact)]).castable,true);
assert.equal(status(aura('nonartifact creature'),[own(permanent('Test Machine','Artifact Creature — Construct'))]).castable,false);
assert.equal(status(aura('nonlegendary creature'),[own(permanent('Test Legend','Legendary Creature — Scout'))]).castable,false);
assert.equal(status(aura('legendary creature'),[own(permanent('Test Legend','Legendary Creature — Scout'))]).castable,true);
assert.equal(status(aura(),[own({...scout,oracle_text:'Hexproof\nWard {2}'})]).castable,true,'own ward/hexproof does not forbid own Auras');
assert.equal(status(aura(),[own({...scout,oracle_text:'Shroud'})]).castable,false);
assert.equal(status(aura(),[own({...scout,oracle_text:"This creature can't be enchanted."})]).castable,false);
assert.equal(status(aura(),[own({...scout,oracle_text:'Protection from white'})]).status,'unmodeled');
assert.equal(status(aura(),[own({...scout,oracle_text:"This creature can't be enchanted as long as you control an artifact."})]).status,'unmodeled');
assert.equal(status(aura(),[{...own(scout),targetingUnmodeled:true}]).status,'unmodeled');
assert.equal(status(aura(),[own({...scout,oracle_text:'This creature has shroud as long as it is untapped.'})]).status,'unmodeled');
assert.equal(status(aura(),[own({...scout,oracle_text:'Protection from white'}),own(scout)]).targetIndex,1,'known eligible host can be used instead');
for(const rule of ['creature with power 2 or less','tapped creature','player','creature with another Aura attached to it'])assert.equal(mtgAuraTargetProfile(aura(rule)).status,'unmodeled',rule);
assert.equal(mtgAuraTargetProfile({...aura(),oracle_text:'No recognized restriction.'}).status,'unmodeled');
const simulate=(rs,opts={})=>mtgGoldfish(rs.map(([qty,c])=>({qty,c})),{runs:80,seed:29,plan:'Aggro',...opts});
const noHost=simulate([[28,plains],[32,aura()]]);
assert.ok(noHost.samples.every(s=>s.log.every(l=>!l.text.includes('Test Aura'))),'no creature means no creature-Aura cast');
assert.equal(noHost.metrics.find(m=>m.label==='Mana used, turns 1–4').value,0,'illegal Aura does not consume mana or count as a play');
const valid=simulate([[20,plains],[20,scout],[20,aura()]]);
assert.ok(valid.samples.some(s=>s.log.some(l=>l.text.includes('Test Aura'))),'legal Aura still casts');
for(const sample of valid.samples){let carrier=false;for(const line of sample.log)for(const action of line.text.split(' · ')){if(action==='Test Scout')carrier=true;if(action==='Test Aura')assert.ok(carrier,'Aura follows a creature, including same-turn sequencing');}}
const opponent=simulate([[20,plains],[20,scout],[20,aura('creature an opponent controls')]]);
assert.ok(opponent.samples.every(s=>s.log.every(l=>!l.text.includes('Test Aura'))),'solitaire has no enemy permanent to enchant');
const wrongType=simulate([[20,plains],[20,artifact],[20,aura()]]);
assert.ok(wrongType.samples.every(s=>s.log.every(l=>!l.text.includes('Test Aura'))),'noncreature permanent cannot host creature Aura');
const landAura=simulate([[30,plains],[30,aura('land')]]);
assert.ok(landAura.samples.some(s=>s.log.some(l=>l.text.includes('Test Aura'))),'played lands are valid modeled hosts');
const artifactAura=simulate([[20,plains],[20,artifact],[20,aura('artifact')]]);
assert.ok(artifactAura.samples.some(s=>s.log.some(l=>l.text.includes('Test Aura'))),'played noncreature permanents are tracked as hosts');
const shroudAura={...aura(),oracle_text:'Enchant creature you control\nEnchanted creature has shroud.'};
const grants=simulate([[20,plains],[20,scout],[20,shroudAura]]);
for(const sample of grants.samples){let hosts=0,attached=0;for(const line of sample.log)for(const action of line.text.split(' · ')){if(action==='Test Scout')hosts++;if(action==='Test Aura')assert.ok(++attached<=hosts,'unmodeled granted shroud cannot be ignored for later Aura casts');}}
assert.equal(grants.auraCasting.status,'partial');
const unknown=simulate([[20,plains],[20,scout],[20,aura('creature with power 2 or less')]]);
assert.equal(unknown.auraCasting.status,'partial');
assert.equal(unknown.auraCasting.unmodeled.length,1);
assert.match(unknown.auraCasting.unmodeled[0].reason,/outside the supported/);
assert.ok(unknown.samples.every(s=>s.log.every(l=>!l.text.includes('Test Aura'))));
assert.match(unknown.limitations.join(' '),/Unknown qualifiers/,'the rendered limitations disclose the target coverage gap');
const bear={...permanent('Test Bear','Creature — Bear'),cmc:2,mana_cost:'{1}{W}'};
const spark={...permanent('Test Spark','Instant','Test Spark deals 3 damage to any target.'),power:undefined};
const ordinary=simulate([[24,plains],[12,scout],[12,bear],[12,spark]]);
assert.equal(createHash('sha256').update(JSON.stringify(ordinary)).digest('hex'),'21fbba656cd57ba5b8d62dcd26efb99600dfd44a2d0eadfcbb24a296877b77f8','seeded non-Aura simulation remains byte-for-byte unchanged');
assert.equal(ordinary.auraCasting,undefined);
console.log('PASS: bounded Aura host/type/controller gating, unknown restriction disclosure, legal same-turn casts, no empty-board casts, and unchanged non-Aura simulation.');
